"""Chapter-by-chapter review criteria aligned with the workspace care-study template."""

CARE_STUDY_REVIEW_RUBRIC = """
CARE-STUDY REVIEW STANDARD

Apply the following chapter-specific criteria to the uploaded study. These are
an editorial and educational checklist based on this project's six-chapter
care-study template; they are not a substitute for a school's current marking
rubric, a clinical guideline, or a qualified clinician's judgment. Review only
chapters and criteria for which the document provides evidence. Mark absent,
unreadable, or ambiguous material "Not assessable from this document"; do not
assume that a missing section means the care was not performed.

Preliminary pages and introduction (P.1-P.3):
- Check that the introduction explains the study's purpose, uses a consistent
  patient pseudonym, and summarizes the admission-to-discharge story without
  introducing facts that conflict with later chapters.
- Check that acknowledgements and preface are relevant and professionally
  worded. Do not expose unnecessary patient-identifying information.

Chapter 1 — Assessment (sections 1.1-1.11):
- 1.1 Particulars: check required identity/admission fields are present as
  appropriate, the admission diagnosis agrees with 1.8 and the introduction,
  dates and demographics are internally consistent, and identifying details
  are minimized in shared/exported work.
- 1.2-1.6 History: check family medical/surgical history, socio-economic
  context, developmental history, lifestyle, and past medical/surgical/
  obstetric history are clearly attributed to the patient/informant, relevant,
  and not contradictory across sections. Treat unknown or not-applicable
  information as something to clarify, not as a negative finding.
- 1.7 Present history: check the illness timeline, presenting/associated
  symptoms, physical findings, investigations/results, medication/history,
  and vital signs for clear units, dates, and internal consistency. Distinguish
  reported symptoms from observed findings.
- 1.8 Admission: check route, date/time, admitting diagnosis, admission
  findings/investigations, and documented initial treatment agree with 1.1,
  1.7, and the introduction.
- 1.9 Patient's concept of illness: distinguish the patient's beliefs and
  understanding from established clinical findings.
- 1.10 Literature review: check the topic matches the documented diagnosis,
  claims have traceable citations, and literature is distinguished from
  patient-specific findings. Do not judge clinical accuracy without relevant
  supplied reference evidence.
- 1.11 Validation: check validation statements are supported by the sources
  described (patient, family, records, observations) and do not claim
  confirmation not shown elsewhere.

Chapter 2 — Analysis of Data (sections 2.1-2.5):
- 2.1 Comparison with standards: check comparisons distinguish literature
  findings from this patient's findings; reported percentages/counts agree
  with their stated numerator and denominator; investigations, clinical
  features, treatments, and complications can be traced to cited sources and
  Chapter 1. Flag unsupported comparisons; do not endorse a clinical standard
  from memory.
- 2.2 Pharmacology: for each drug listed, check whether the document supplies
  drug/class, dose, route, frequency, indication, side effects, and nursing
  responsibilities as required by the template; compare names and details
  consistently with documented medication/treatment sections (1.6, 1.8, 2.1,
  4.1, 4.2). Flag missing, conflicting, or unreferenced details for
  verification. Do not declare a drug, dose, or regimen wrong or recommend a
  medication change without a directly relevant supplied authoritative source
  and adequate context.
- 2.3 Problems: distinguish actual problems from potential/risk problems and
  trace each to the patient's reported or observed assessment evidence.
  Check prioritization is stated and consistent with the rationale given.
- 2.4 Strengths: check general and problem-specific strengths are supported by
  documented patient/family information and linked to relevant problems.
- 2.5 Nursing diagnoses: check every diagnosis maps to an identified problem
  and assessment evidence; actual diagnoses use the school's stated
  problem/etiology/evidence format where supported, while risk diagnoses are
  not presented as confirmed actual problems. Check priorities and terminology
  are consistent across 2.3-2.5 and Chapter 3. Do not certify NANDA-I validity
  unless an applicable supplied reference supports it.

Chapter 3 — Planning (sections 3.1-3.2):
- 3.1 Objectives: check objectives relate to identified patient/family
  problems, state an observable/measurable outcome and a timeframe, and have
  outcome criteria that can later be evaluated. Flag vague, unmeasurable,
  conflicting, or unsupported targets; do not invent baselines or outcomes.
- 3.2 Care plan: check each row's diagnosis matches Chapter 2; objective/
  outcome criteria match 3.1; orders are identifiable as planned actions;
  interventions are distinguishable from orders and are not represented as
  completed care unless documented; evaluation has a corresponding outcome and
  date/time when available; and rationale is linked to the row and has a
  citation when a clinical claim requires one. Check dates and medication
  details against the rest of the study. Flag potential clinical
  appropriateness questions for a qualified reviewer, not as definitive
  errors.

Chapter 4 — Implementation (sections 4.1-4.3):
- 4.1 Actual care: check narrative is about care documented as performed, with
  its timeline, procedures, medication/treatment details, education, and
  family involvement consistent with Chapters 1-3. A planned order alone is
  not evidence that an intervention occurred.
- 4.2 Discharge preparation: check the documented education, responsibilities,
  resources/referrals, discharge process, discharge date, and review date agree
  with the patient's documented condition and other dates. Do not infer
  counseling, medication instructions, referrals, or clinical readiness.
- 4.3 Follow-up/home visits: check visit sequence and dates against discharge
  and review dates; each described objective, finding, education, outcome,
  and handover is supported by the text. The template describes a
  pre-discharge visit and preferably three follow-up visits; report departures
  as template differences, not universal clinical requirements.

Chapter 5 — Evaluation (sections 5.1-5.3):
- 5.1 Evaluation: check each care-plan diagnosis/objective has a corresponding
  outcome; the stated fully/partially/not-met status agrees with the recorded
  evidence and timeframe; overall claims agree with the individual outcomes;
  and follow-up/referrals are consistent with Chapter 4.
- 5.2 Amendments: when outcomes are partially met or unmet, check the stated
  amendment and reason are documented and linked to the relevant diagnosis and
  outcome. Do not invent a revised order or claim an amendment occurred.
- 5.3 Termination: check the account of ending the nurse-patient interaction,
  patient/family involvement, and handover/continuity arrangements agrees with
  follow-up and discharge sections. Do not claim a referral or handover absent
  evidence.

Chapter 6 — Summary, conclusion, and bibliography (sections 6.1-6.3):
- Summary: check it accurately synthesizes the study and its timeline,
  assessment, analysis, care, and evaluation without adding new patient facts
  or contradicting earlier chapters.
- Conclusion: check it follows from the documented care and outcomes and does
  not introduce new findings, unsupported claims, or claims of success that
  conflict with Chapter 5.
- Bibliography: check each in-text citation has a corresponding reference and
  listed sources are cited in the text, with enough information to identify
  them. Flag unverifiable sources and formatting inconsistencies; do not
  fabricate bibliographic details or claim a source is authoritative without
  verification.

Cross-chapter checks:
- Trace key facts (pseudonym, age where relevant, diagnosis, symptoms,
  findings, investigations, medication details, admission/discharge/review
  dates, problems, diagnoses, objectives, care, and outcomes) to their
  occurrences and flag direct contradictions with section-level evidence.
- Trace the care-study reasoning chain: assessment evidence -> problems and
  strengths -> nursing diagnoses -> objectives/outcome criteria -> planned
  orders -> documented interventions -> evaluation -> amendments/follow-up/
  termination -> summary and conclusion.
- Separate (1) definite contradiction, (2) template/structural gap,
  (3) unsupported or unreferenced claim, and (4) item needing human/clinical
  verification. Do not label a missing detail or template difference a
  clinical error.
"""

RM_CARE_STUDY_REVIEW_RUBRIC_DRAFT = """
PROVISIONAL REGISTERED MIDWIFERY CARE-STUDY REVIEW CHECKLIST — NOT APPROVED

This draft is an editorial consistency checklist synthesized from four
user-supplied RM student care-study examples in attached_assets/RM cadre. Those
examples vary in headings, numbering, and organization. The draft is not an
N&MC rubric, an institutional marking scheme, or a clinical guideline. It must
remain unavailable to student review until an RM educator reconciles it with
the current programme instructions and approves the template and criteria.

Review only what the uploaded document supports. Mark absent, unreadable, or
ambiguous details "Not assessable from this document." A missing entry does not
prove care was not provided. Treat departures from this draft as possible
format differences, not clinical errors.

Preliminary pages:
- Check that title, declaration, acknowledgements, contents, and abbreviations
  are consistent with one another and the institution's supplied requirements.
- Flag unnecessary patient identifiers in shared work. Do not invent required
  wording for declarations or institutional front matter.

Phase 1 — Client and pregnancy assessment:
- Check that relevant social, family, medical, surgical, menstrual, and past
  obstetric histories are distinguishable, attributed where possible, and
  consistent within the document.
- Check that the present pregnancy account separates client-reported history,
  observed findings, and record-derived information. Dates, gestational-age
  references, units, and described results should not contradict one another.
- Check that the introduction and phase summaries do not add patient facts
  absent from the assessment or supplied records.
- Do not infer a risk status, diagnosis, or clinical significance not
  documented or supported by an applicable supplied source.

Phase 2 — Antenatal care:
- Check that the first contact, clinic contacts, home visits, care plans, and
  evaluations have a traceable chronology. Flag missing or contradictory dates
  without assuming which date is correct.
- For each care-plan entry, trace the stated problem or diagnosis to assessment
  evidence; check that the objective has observable outcome criteria and a
  timeframe; and distinguish planned care from care documented as delivered.
- Check that evaluation refers to the same objective and reports evidence
  recorded in the document. Where an outcome is partly met or unclear, flag the
  gap rather than inventing a result or amendment.
- Compare clinical claims or instructions only with relevant sources supplied
  or institutionally approved. Do not certify a regimen, investigation, or
  intervention from model memory.

Phase 3 — Labour and delivery:
- Check the account is chronological across admission, labour stages, birth,
  immediate newborn care, placental/membrane findings, and early post-delivery
  observations. Flag contradictory times, dates, sequences, or recorded
  values.
- Where labour charts or records are included, check that narrative summaries
  agree with the recorded material and clearly identify unavailable or
  unreadable chart information. Do not derive missing observations.
- Check that maternal and newborn findings are not conflated, and that care
  described as performed has evidence in the narrative or supplied record.
- Check labour-phase diagnoses or problems, objectives, plans, documented
  interventions, and evaluation for traceable links. Refer questions about
  clinical appropriateness, escalation, or protocol compliance to an RM
  educator using the applicable current guideline.

Phase 4 — Puerperium and postnatal care:
- Check that the maternal and newborn accounts are distinguishable, and that
  postnatal observations, care, education, discharge, home/clinic follow-up,
  and outcomes follow a consistent timeline.
- Trace each phase-specific care-plan item from evidence through objective,
  documented care, and evaluation. Do not treat a planned action as proof it
  occurred or as proof of a clinical outcome.
- Flag missing documentation of follow-up or continuity as a documentation
  gap only; do not conclude that follow-up or referral did not happen.
- Do not judge maternal or newborn management without adequate context and
  the applicable approved source.

Phase 5 — Summary, conclusion, references, appendices:
- Check the summary and conclusion reflect the documented antenatal, labour,
  birth, and postnatal course without adding facts or overstating outcomes.
- Check that in-text citations map to identifiable bibliography entries and
  that cited clinical claims can be traced to supplied sources. Do not invent
  bibliographic details or claim source authority without verification.
- Check appendices referenced in the narrative are present and readable where
  supplied. Avoid repeating unnecessary identifiers; do not infer missing
  records.

Cross-phase consistency:
- Trace key dates, pregnancy history, maternal findings, labour timeline,
  newborn information, treatments as recorded, care-plan entries, and outcomes
  across phases; report direct contradictions with their document locations.
- Trace the reasoning chain: assessment evidence -> identified needs/problems
  -> objectives -> planned care -> documented care -> evaluation ->
  follow-up -> summary and conclusion.
- Classify each finding as a definite document contradiction, a structural or
  documentation gap, an unsupported claim, or an item requiring RM educator/
  clinical verification. Keep clinical verification separate from editorial
  findings and do not prescribe changes to patient care.
"""

